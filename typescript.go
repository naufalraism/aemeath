// TypeScriptClient generates TypeScript source (a type-safe client)
// from all registered typed routes.
func (a *App) TypeScriptClient() string {
	g := newTSGen()
	for _, s := range a.specs {
		g.scanInput(s.in, s.method)
		g.scanOutput(s.out)
	}
	g.assignNames()

	var ops []tsOp
	usedOps := map[string]bool{}
	for _, s := range a.specs {
		base := tsIdent(s.opID())
		name := base
		for i := 2; usedOps[name]; i++ {
			name = base + strconv.Itoa(i)
		}
		if name != base {
			log.Printf("aemeath: warning: operation name %q is already taken, using %q", base, name)
		}
		usedOps[name] = true
		ops = append(ops, g.operation(s, name))
	}

	var b strings.Builder
	b.WriteString("// Generated by Aemeath. Do not edit manually.\n/* eslint-disable */\n\n")
	for _, e := range g.order {
		if e.inName != "" {
			fmt.Fprintf(&b, "export interface %s {\n", e.inName)
			for _, line := range g.fields(e.typ, 0, true) {
				fmt.Fprintf(&b, "  %s;\n", line)
			}
			b.WriteString("}\n\n")
		}
		if e.outName != "" {
			fmt.Fprintf(&b, "export interface %s {\n", e.outName)
			for _, line := range g.fields(e.typ, 0, false) {
				fmt.Fprintf(&b, "  %s;\n", line)
			}
			b.WriteString("}\n\n")
		}
	}
	b.WriteString(tsRuntime)
	b.WriteString("\nexport function createClient(opts: ClientOptions) {\n  return {\n")
	for _, op := range ops {
		b.WriteString(op.code)
	}
	b.WriteString("  };\n}\n\nexport type Client = ReturnType<typeof createClient>;\n")
	return b.String()
}

// inputMode says whether a generated client function takes an input argument.
type inputMode int

const (
	noInput inputMode = iota
	optionalInput
	requiredInput
)

// tsOp is one generated client function.
type tsOp struct {
	name   string
	method string
	code   string
	mode   inputMode
	spec   routeSpec
}

// WriteTypeScript writes client.ts, schemas.ts (Zod) and hooks.ts (React
// Query) into dir, creating it if needed.
//
// A file whose content is already identical is left untouched, so a bundler
// watching the directory (Vite, webpack) does not reload for nothing, and every
// write goes through a temporary file, so a reader never sees a half-written one.
func (a *App) WriteTypeScript(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	files := []struct{ name, content string }{
		{"client.ts", a.TypeScriptClient()},
		{"schemas.ts", a.ZodSchemas()},
		{"hooks.ts", a.ReactQueryHooks()},
	}
	for _, f := range files {
		if err := writeFileIfChanged(filepath.Join(dir, f.name), []byte(f.content)); err != nil {
			return err
		}
	}
	return nil
}

// writeFileIfChanged writes content to path unless the file already has exactly that content.
func writeFileIfChanged(path string, content []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, content) {
		return nil
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".aemeath-*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	if _, err := tmp.Write(content); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmpName)
		return err
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(tmpName)
		return err
	}
	if err := os.Chmod(tmpName, 0o644); err != nil {
		_ = os.Remove(tmpName)
		return err
	}
	if err := os.Rename(tmpName, path); err != nil {
		_ = os.Remove(tmpName)
		return err
	}
	return nil
}

// WriteTypeScriptClient writes the TypeScript client to a file.
func (a *App) WriteTypeScriptClient(path string) error {
	return os.WriteFile(path, []byte(a.TypeScriptClient()), 0o644)
}

// EnableClient registers the generated TypeScript sources:
//
//	GET /client.ts    typed fetch client
//	GET /schemas.ts   Zod schemas (needs the "zod" package)
//	GET /hooks.ts     React Query hooks (needs "@tanstack/react-query")
func (a *App) EnableClient() {
	serve := func(path string, gen func() string) {
		var (
			mu          sync.Mutex
			cached      string
			cachedCount = -1
		)
		a.Handle("GET", path, func(c *Ctx) error {
			mu.Lock()
			if cachedCount != len(a.specs) {
				cached = gen()
				cachedCount = len(a.specs)
			}
			out := cached
			mu.Unlock()
			c.W.Header().Set("Content-Type", "text/plain; charset=utf-8")
			_, err := io.WriteString(c.W, out)
			return err
		})
	}
	serve("/client.ts", a.TypeScriptClient)
	serve("/schemas.ts", a.ZodSchemas)
	serve("/hooks.ts", a.ReactQueryHooks)
}

const tsRuntime = `export interface FieldError {
  field: string;
  rule: string;
  message: string;
}

export class ApiError extends Error {
  /** Per-field details of a 422 validation failure. */
  public errors: FieldError[];
  constructor(public status: number, message: string, errors: FieldError[] = []) {
    super(message);
    this.name = "ApiError";
    this.errors = errors;
  }
}

export interface ClientOptions {
  baseUrl: string;
  fetch?: typeof fetch;
  headers?: Record<string, string> | (() => Record<string, string>);
}

interface RequestInput {
  path?: Record<string, unknown>;
  query?: Record<string, unknown>;
  headers?: Record<string, unknown>;
  body?: unknown;
}

async function request<T>(opts: ClientOptions, method: string, path: string, input: RequestInput): Promise<T> {
  const url = path.replace(/\{([^}]+)\}/g, (_, k: string) => encodeURIComponent(String(input.path?.[k])));
  const qs = new URLSearchParams();
  for (const [k, v] of Object.entries(input.query ?? {})) {
    if (v === undefined || v === null) continue;
    if (Array.isArray(v)) {
      for (const item of v) qs.append(k, String(item));
    } else {
      qs.set(k, String(v));
    }
  }
  const q = qs.toString();
  const extra = typeof opts.headers === "function" ? opts.headers() : opts.headers;
  const own: Record<string, string> = {};
  for (const [k, v] of Object.entries(input.headers ?? {})) {
    if (v !== undefined && v !== null) own[k] = String(v);
  }
  const f = opts.fetch ?? fetch;
  const res = await f(opts.baseUrl.replace(/\/$/, "") + url + (q ? "?" + q : ""), {
    method,
    headers: { ...(input.body !== undefined ? { "Content-Type": "application/json" } : {}), ...extra, ...own },
    body: input.body !== undefined ? JSON.stringify(input.body) : undefined,
  });
  const text = await res.text();
  let data: any;
  try {
    data = text ? JSON.parse(text) : undefined;
  } catch {
    if (res.ok) throw new ApiError(res.status, "Invalid JSON response");
  }
  if (!res.ok) throw new ApiError(res.status, data?.error ?? res.statusText, data?.errors);
  return data as T;
}
`

type tsEntry struct {
	typ     reflect.Type
	useIn   bool
	useOut  bool
	inName  string
	outName string
}

type tsGen struct {
	entries map[reflect.Type]*tsEntry
	order   []*tsEntry
	used    map[string]bool
}

func newTSGen() *tsGen {
	return &tsGen{
		entries: map[reflect.Type]*tsEntry{},
		used:    map[string]bool{"ApiError": true, "ClientOptions": true, "Client": true, "FieldError": true},
	}
}

func (g *tsGen) scanInput(t reflect.Type, method string) {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return
	}
	for _, f := range flatFields(t) {
		if src, _ := paramSource(f.StructField); src != "" || bodyMethod(method) {
			g.scanType(f.Type, true)
		}
	}
}

func (g *tsGen) scanOutput(t reflect.Type) {
	if t == reflect.TypeFor[Handled]() {
		return
	}
	g.scanType(t, false)
}

func (g *tsGen) scanType(t reflect.Type, input bool) {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if isTextType(t) {
		return
	}
	switch t.Kind() {
	case reflect.Slice, reflect.Array, reflect.Map:
		g.scanType(t.Elem(), input)
		return
	case reflect.Struct:
	default:
		return
	}
	if t.Name() == "" {
		for _, f := range jsonFields(t) {
			if jsonName(f) == "-" {
				continue
			}
			g.scanType(f.Type, input)
		}
		return
	}
	e, ok := g.entries[t]
	if !ok {
		e = &tsEntry{typ: t}
		g.entries[t] = e
		g.order = append(g.order, e)
	}
	if input {
		if e.useIn {
			return
		}
		e.useIn = true
	} else {
		if e.useOut {
			return
		}
		e.useOut = true
	}
	for _, f := range jsonFields(t) {
		if jsonName(f) == "-" {
			continue
		}
		g.scanType(f.Type, input)
	}
}

func (g *tsGen) assignNames() {
	for _, e := range g.order {
		base := upperFirst(tsIdent(e.typ.Name()))
		if base == "" {
			base = "Anonymous"
		}
		both := e.useIn && e.useOut
		if e.useIn {
			name := base
			if both {
				name = base + "In"
			}
			e.inName = g.uniqueName(name)
		}
		if e.useOut {
			name := base
			if both {
				name = base + "Out"
			}
			e.outName = g.uniqueName(name)
		}
	}
}

func (g *tsGen) uniqueName(base string) string {
	name := base
	for i := 2; g.used[name]; i++ {
		name = base + strconv.Itoa(i)
	}
	g.used[name] = true
	return name
}

func (g *tsGen) register(t reflect.Type, input bool) string {
	e := g.entries[t]
	if input {
		return e.inName
	}
	return e.outName
}

func (g *tsGen) typeRef(t reflect.Type, depth int, input bool) string {
	if depth > maxSchemaDepth {
		return "unknown"
	}
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if isTextType(t) {
		return "string"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string"
		}
		return "Array<" + g.typeRef(t.Elem(), depth+1, input) + ">"
	case reflect.Array:
		return "Array<" + g.typeRef(t.Elem(), depth+1, input) + ">"
	case reflect.Map:
		return "Record<string, " + g.typeRef(t.Elem(), depth+1, input) + ">"
	case reflect.Struct:
		if t.Name() != "" {
			return g.register(t, input)
		}
		lines := g.fields(t, depth+1, input)
		if len(lines) == 0 {
			return "Record<string, never>"
		}
		return "{ " + strings.Join(lines, "; ") + " }"
	}
	return "unknown"
}

func (g *tsGen) fields(t reflect.Type, depth int, input bool) []string {
	var lines []string
	for _, f := range jsonFields(t) {
		if line, ok := g.field(f, depth, input); ok {
			lines = append(lines, line)
		}
	}
	return lines
}

func (g *tsGen) field(f reflect.StructField, depth int, input bool) (string, bool) {
	if !f.IsExported() {
		return "", false
	}
	name := jsonName(f)
	if name == "-" {
		return "", false
	}
	typ := g.fieldType(f, depth, input)
	opt := hasOmitEmpty(f)
	if input {
		opt = !inputRequired(f)
	}
	return tsDoc(f, input) + tsField(name, typ, opt), true
}

// fieldType is the TypeScript type of a field: a literal union for `oneof`
// (input only), otherwise the plain type, plus null where Go can send null.
func (g *tsGen) fieldType(f reflect.StructField, depth int, input bool) string {
	typ := ""
	if input {
		typ = oneofUnion(f)
	}
	if typ == "" {
		typ = g.typeRef(f.Type, depth, input)
	}
	// A nil pointer, slice, or map is encoded as JSON null in responses. In a
	// request, null is only accepted where the field is optional.
	if (f.Type.Kind() == reflect.Pointer && !(input && hasRequired(f))) || (!input && nilable(f.Type)) {
		typ += " | null"
	}
	return typ
}

// oneofUnion turns `validate:"oneof=a b c"` into "a" | "b" | "c".
func oneofUnion(f reflect.StructField) string {
	if !strings.Contains(f.Tag.Get("validate"), "oneof") {
		return ""
	}
	_, rules := parseRules(reflect.TypeOf(struct{}{}), f)
	for _, r := range rules {
		if r.name != "oneof" {
			continue
		}
		var parts []string
		if classOf(f.Type) == kindNumber {
			for _, s := range r.set {
				parts = append(parts, s)
			}
		} else {
			for _, s := range r.set {
				parts = append(parts, strconv.Quote(s))
			}
		}
		return strings.Join(parts, " | ")
	}
	return ""
}

// tsDoc builds a JSDoc comment from the description tag and the input constraints.
func tsDoc(f reflect.StructField, input bool) string {
	var parts []string
	if d := f.Tag.Get("description"); d != "" {
		parts = append(parts, d)
	}
	if input {
		c := ruleConstraints(f)
		for _, k := range []string{"minLength", "maxLength", "minimum", "maximum", "minItems", "maxItems", "minProperties", "maxProperties", "format", "pattern"} {
			if v, ok := c[k]; ok {
				parts = append(parts, fmt.Sprintf("@%s %v", k, v))
			}
		}
		if c["exclusiveMinimum"] == true {
			parts = append(parts, "(minimum is exclusive)")
		}
		if c["exclusiveMaximum"] == true {
			parts = append(parts, "(maximum is exclusive)")
		}
	}
	if ex := f.Tag.Get("example"); ex != "" {
		parts = append(parts, "@example "+ex)
	}
	if len(parts) == 0 {
		return ""
	}
	doc := strings.NewReplacer("*/", "* /", "\n", " ", "\r", " ").Replace(strings.Join(parts, " "))
	return "/** " + doc + " */ "
}

func (g *tsGen) operation(s routeSpec, name string) tsOp {
	t := s.in
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	var pathP, queryP, headerP, bodyP []string
	queryReq, headerReq, bodyReq := false, false, false
	declared := map[string]bool{}
	if t.Kind() == reflect.Struct {
		for _, ff := range flatFields(t) {
			f := ff.StructField
			src, pname := paramSource(f)
			switch {
			case src == "path":
				pathP = append(pathP, tsDoc(f, true)+tsField(pname, g.fieldType(f, 1, true), false))
				declared[pname] = true
			case src == "query":
				opt := !hasRequired(f)
				queryP = append(queryP, tsDoc(f, true)+tsField(pname, g.fieldType(f, 1, true), opt))
				if !opt {
					queryReq = true
				}
			case src == "header":
				opt := !hasRequired(f)
				headerP = append(headerP, tsDoc(f, true)+tsField(pname, g.fieldType(f, 1, true), opt))
				if !opt {
					headerReq = true
				}
			case src == "cookie":
				// Cookies are managed by the browser; they cannot be set from fetch.
			case bodyMethod(s.method):
				if line, ok := g.field(f, 1, true); ok {
					bodyP = append(bodyP, line)
					if inputRequired(f) {
						bodyReq = true
					}
				}
			}
		}
	}
	for _, m := range pathParamRe.FindAllStringSubmatch(s.path, -1) {
		if !declared[m[1]] {
			pathP = append(pathP, tsField(m[1], "string", false))
			declared[m[1]] = true
		}
	}

	var segs []string
	needInput := false
	if len(pathP) > 0 {
		segs = append(segs, "path: { "+strings.Join(pathP, "; ")+" }")
		needInput = true
	}
	if len(queryP) > 0 {
		segs = append(segs, "query"+optMark(!queryReq)+": { "+strings.Join(queryP, "; ")+" }")
		needInput = needInput || queryReq
	}
	if len(headerP) > 0 {
		segs = append(segs, "headers"+optMark(!headerReq)+": { "+strings.Join(headerP, "; ")+" }")
		needInput = needInput || headerReq
	}
	if len(bodyP) > 0 {
		segs = append(segs, "body"+optMark(!bodyReq)+": { "+strings.Join(bodyP, "; ")+" }")
		needInput = needInput || bodyReq
	}
	sig, arg := "", "{}"
	mode := noInput
	if len(segs) > 0 {
		obj := "{ " + strings.Join(segs, "; ") + " }"
		if needInput {
			sig, arg, mode = "input: "+obj, "input", requiredInput
		} else {
			sig, arg, mode = "input?: "+obj, "input ?? {}", optionalInput
		}
	}

	var b strings.Builder
	if s.cfg.summary != "" {
		doc := strings.NewReplacer("*/", "* /", "\n", " ").Replace(s.cfg.summary)
		fmt.Fprintf(&b, "    /** %s */\n", doc)
	}
	fmt.Fprintf(&b, "    %s: (%s) =>\n", name, sig)
	fmt.Fprintf(&b, "      request<%s>(opts, %s, %s, %s),\n", g.outType(s), strconv.Quote(s.method), strconv.Quote(openAPIPath(s.path)), arg)
	return tsOp{name: name, method: s.method, code: b.String(), mode: mode, spec: s}
}

// outType is the TypeScript type of the response body.
func (g *tsGen) outType(s routeSpec) string {
	switch {
	case s.out == reflect.TypeFor[Handled]():
		return "unknown"
	case !bodyAllowed(s.cfg.status):
		return "void"
	}
	out := g.typeRef(s.out, 0, false)
	if nilable(s.out) {
		out += " | null"
	}
	return out
}

func optMark(opt bool) string {
	if opt {
		return "?"
	}
	return ""
}

func tsField(name, typ string, opt bool) string {
	return tsKey(name) + optMark(opt) + ": " + typ
}

var tsKeyRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func tsKey(name string) string {
	if tsKeyRe.MatchString(name) {
		return name
	}
	return strconv.Quote(name)
}

// hasOmitEmpty reports whether the json tag contains omitempty or omitzero.
func hasOmitEmpty(f reflect.StructField) bool {
	_, opts, _ := strings.Cut(f.Tag.Get("json"), ",")
	for _, o := range strings.Split(opts, ",") {
		if o == "omitempty" || o == "omitzero" {
			return true
		}
	}
	return false
}

func (s routeSpec) opID() string {
	if s.cfg.opID != "" {
		return s.cfg.opID
	}
	var b strings.Builder
	b.WriteString(strings.ToLower(s.method))
	trimmed := strings.Trim(openAPIPath(s.path), "/")
	if trimmed == "" {
		b.WriteString("Root")
	}
	for _, seg := range strings.Split(trimmed, "/") {
		if seg == "" {
			continue
		}
		if m := pathParamRe.FindStringSubmatch(seg); m != nil && m[0] == seg {
			fmt.Fprintf(&b, "By%s", pascal(m[1]))
			continue
		}
		b.WriteString(pascal(seg))
	}
	return b.String()
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

func pascal(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
	var b strings.Builder
	for _, p := range parts {
		b.WriteString(upperFirst(p))
	}
	return b.String()
}

func tsIdent(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r < 128 && (unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_') {
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "op" + out
	}
	return out
}

// nilable reports whether a nil value of t is encoded as JSON null
// (a nil slice or map, which is easy to forget to initialize).
func nilable(t reflect.Type) bool {
	return t.Kind() == reflect.Slice || t.Kind() == reflect.Map
}
