package drivers

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/naufalraism/aemeath"
	"github.com/naufalraism/aemeath/db"
	"github.com/naufalraism/aemeath/db/mysql"
	"github.com/naufalraism/aemeath/db/postgres"
	"github.com/naufalraism/aemeath/db/sqlite"
)

// Uses tags that only PostgreSQL understands: migrating it on a real SQLite
// database would fail, so this also proves no SQL is executed.
type pgOnly struct {
	ID    string `gorm:"type:uuid;primaryKey;default:gen_random_uuid()"`
	Title string `gorm:"type:text"`
}

// "aemeath ts" runs the program only to write TypeScript. With PostgreSQL or
// MySQL that used to require a running server (main exits when Open fails),
// and with SQLite it created and migrated the real database file.
func TestOpenNeedsNoDatabaseWhileGeneratingTypeScript(t *testing.T) {
	t.Setenv(aemeath.EnvTypeScriptOut, t.TempDir())
	if !aemeath.GeneratingTypeScript() {
		t.Fatal("GeneratingTypeScript() = false with AEMEATH_TS_OUT set")
	}

	// Nothing listens on port 1: a real connection attempt would fail.
	for name, open := range map[string]func() (*db.Plugin, error){
		"postgres": func() (*db.Plugin, error) {
			return postgres.Open("postgres://u:p@127.0.0.1:1/app?sslmode=disable&connect_timeout=1", db.WithModels(&pgOnly{}))
		},
		"mysql": func() (*db.Plugin, error) {
			return mysql.Open("u:p@tcp(127.0.0.1:1)/app?timeout=1s", db.WithModels(&pgOnly{}))
		},
	} {
		t.Run(name, func(t *testing.T) {
			p, err := open()
			if err != nil {
				t.Fatalf("Open while generating TypeScript: %v", err)
			}
			defer func() { _ = p.Close() }()
			// Handlers generated by the CLI migrate their own model at startup.
			if err := p.DB.AutoMigrate(&pgOnly{}); err != nil {
				t.Fatalf("AutoMigrate: %v", err)
			}
			var rows []pgOnly
			if err := p.DB.Find(&rows).Error; err != nil {
				t.Fatalf("query at startup: %v", err)
			}
		})
	}

	// The SQLite file of the project is not created or touched.
	file := filepath.Join(t.TempDir(), "app.db")
	p, err := sqlite.Open(file, db.WithModels(&pgOnly{}))
	if err != nil {
		t.Fatalf("sqlite.Open: %v", err)
	}
	_ = p.Close()
	if _, err := os.Stat(file); !os.IsNotExist(err) {
		t.Fatalf("%s was created while only generating TypeScript", file)
	}
}
