// ZodSchemas generates a TypeScript file with Zod schemas for every request
// and response type, plus one schema per operation input (path, query,
// headers, body). The `validate` rules become Zod checks, so a form can be
// validated in the browser with exactly the rules the server enforces.
//
// Note: `pattern` rules are Go (RE2) regular expressions and are passed to
// JavaScript's RegExp unchanged; stick to the common syntax.
func (a *App) ZodSchemas() string {
	g := newTSGen()
	for _, s := range a.specs {
		g.scanInput(s.in, s.method)
		g.scanOutput(s.out)
	}
	g.assignNames()

	var b strings.Builder
	b.WriteString("// Generated by Aemeath. Do not edit manually.\n/* eslint-disable */\n\nimport { z } from \"zod\";\n\n")

	emit := func(name string, e *tsEntry, input bool) {
		fmt.Fprintf(&b, "export interface %s {\n", name)
		for _, line := range g.fields(e.typ, 0, input) {
			fmt.Fprintf(&b, "  %s;\n", line)
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "export const %sSchema: z.ZodType<%s> = z.object({\n", name, name)
		for _, line := range g.zodFields(e.typ, input) {
			fmt.Fprintf(&b, "  %s,\n", line)
		}
		b.WriteString("});\n\n")
	}
	for _, e := range g.order {
		if e.inName != "" {
			emit(e.inName, e, true)
		}
		if e.outName != "" {
			emit(e.outName, e, false)
		}
	}

	// One schema per operation input part.
	used := map[string]bool{}
	for _, s := range a.specs {
		base := tsIdent(s.opID())
		name := base
		for i := 2; used[name]; i++ {
			name = base + strconv.Itoa(i)
		}
		used[name] = true
		inputs := g.zodInputParts(s)
		for _, part := range []string{"Path", "Query", "Headers", "Form", "Body"} { // a fixed order keeps the output stable
			lines := inputs[part]
			if len(lines) == 0 {
				continue
			}
			fmt.Fprintf(&b, "export const %s%sSchema = z.object({\n", name, part)
			for _, l := range lines {
				fmt.Fprintf(&b, "  %s,\n", l)
			}
			b.WriteString("});\n\n")
		}
	}
	return b.String()
}

// zodInputParts returns the Zod fields of an operation's path, query, header
// and body inputs, keyed by the suffix of the generated schema name.
func (g *tsGen) zodInputParts(s routeSpec) map[string][]string {
	parts := map[string][]string{"Path": nil, "Query": nil, "Headers": nil, "Form": nil, "Body": nil}
	t := s.in
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return parts
	}
	for _, ff := range flatFields(t) {
		f := ff.StructField
		src, pname := paramSource(f)
		key := ""
		name := jsonName(f)
		switch {
		case src == "path":
			key, name = "Path", pname
		case src == "query":
			key, name = "Query", pname
		case src == "header":
			key, name = "Headers", pname
		case src == "cookie":
			continue
		case formName(f) != "":
			key, name = "Form", formName(f)
		case bodyMethod(s.method):
			key = "Body"
		default:
			continue
		}
		if jsonSkipped(f) && src == "" {
			continue
		}
		parts[key] = append(parts[key], g.zodFieldNamed(f, name, true))
	}
	return parts
}

func (g *tsGen) zodFields(t reflect.Type, input bool) []string {
	var lines []string
	for _, f := range jsonFields(t) {
		if jsonSkipped(f) {
			continue
		}
		lines = append(lines, g.zodFieldNamed(f, jsonName(f), input))
	}
	return lines
}

func (g *tsGen) zodFieldNamed(f reflect.StructField, name string, input bool) string {
	var expr string
	switch f.Type {
	case fileHeaderPtrType:
		expr = "z.instanceof(Blob)"
	case fileHeaderSliceType:
		expr = "z.array(z.instanceof(Blob))"
	default:
		expr = g.zodType(f.Type, input)
	}
	quoted := jsonQuoted(f)
	if quoted {
		// `json:",string"`: the value travels as a JSON string. Numeric rules
		// are enforced by the server; here only the format is checked.
		expr = "z.string().regex(/" + quotedPattern(f.Type) + "/)"
	}
	if input && !isFileType(f.Type) && !quoted {
		expr = zodRules(expr, f)
	}
	if acceptsNull(f, input) && expr != "z.unknown()" {
		expr += ".nullable()"
	}
	optional := outputOptional(f)
	if input {
		optional = !inputRequired(f)
	}
	if _, src := paramSource(f); src != "" && f.Tag.Get("path") != "" {
		optional = false
	}
	if optional {
		expr += ".optional()"
	}
	return tsKey(name) + ": " + expr
}

func (g *tsGen) zodType(t reflect.Type, input bool) string {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == timeType {
		return `z.string().datetime({ offset: true })`
	}
	if isCustomJSON(t) {
		return "z.unknown()" // MarshalJSON / json.RawMessage: any JSON value
	}
	if isTextType(t) {
		if t.Name() == "UUID" {
			return "z.string()" + zodFormat(uuidPattern, "Invalid UUID")
		}
		return "z.string()"
	}
	switch t.Kind() {
	case reflect.String:
		return "z.string()"
	case reflect.Bool:
		return "z.boolean()"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return "z.number().int()" + zodRange(t.Kind())
	case reflect.Float32, reflect.Float64:
		return "z.number()" + zodRange(t.Kind())
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			return "z.string()"
		}
		return "z.array(" + g.zodElem(t.Elem(), input) + ")"
	case reflect.Map:
		return "z.record(z.string(), " + g.zodElem(t.Elem(), input) + ")"
	case reflect.Struct:
		if t.Name() != "" {
			name := g.register(t, input)
			return "z.lazy(() => " + name + "Schema)"
		}
		lines := g.zodFields(t, input)
		if len(lines) == 0 {
			return "z.object({})"
		}
		return "z.object({ " + strings.Join(lines, ", ") + " })"
	}
	return "z.unknown()"
}

// zodFormat checks a string against one of the shared format patterns (see
// formats.go) instead of Zod's own .email()/.url()/.uuid(), which differ from
// the server and between Zod versions.
func zodFormat(pattern, message string) string {
	return ".regex(new RegExp(" + jsString(pattern) + "), " + jsString(message) + ")"
}

// zodElem is the schema of an element of a slice, array or map; see elemRef.
func (g *tsGen) zodElem(t reflect.Type, input bool) string {
	expr := g.zodType(t, input)
	if !input && elemNullable(t) && expr != "z.unknown()" {
		expr += ".nullable()"
	}
	return expr
}

// zodRules appends the Zod checks that correspond to the `validate` rules of f.
func zodRules(expr string, f reflect.StructField) string {
	if f.Tag.Get("validate") == "" {
		return expr
	}
	required, rules := parseRules(reflect.TypeOf(struct{}{}), f)
	class := classOf(f.Type)
	base := f.Type
	for base.Kind() == reflect.Pointer {
		base = base.Elem()
	}
	isMap := base.Kind() == reflect.Map
	if required && !hasPositiveMin(rules) {
		// The server reads an empty string, list or map as missing. (Behind
		// a pointer, only null is missing: "" is a value.)
		switch f.Type.Kind() {
		case reflect.String, reflect.Slice:
			expr += ".min(1)"
		case reflect.Map:
			expr += mapSize(">=", 1)
		}
	}
	for _, r := range rules {
		switch class {
		case kindString:
			switch r.name {
			case "min":
				expr += ".min(" + num(r.num) + ")"
			case "max":
				expr += ".max(" + num(r.num) + ")"
			case "len":
				expr += ".length(" + num(r.num) + ")"
			case "email":
				expr += zodFormat(emailPattern, "Invalid email address")
			case "url":
				expr += zodFormat(urlPattern, "Invalid http(s) URL")
			case "uuid":
				expr += zodFormat(uuidPattern, "Invalid UUID")
			case "pattern":
				// Go and JavaScript regular expressions differ; a pattern that
				// cannot be translated is left to the server.
				if p, flags, ok := jsRegexp(r.arg); ok {
					if flags != "" {
						expr += ".regex(new RegExp(" + jsString(p) + ", " + jsString(flags) + "))"
					} else {
						expr += ".regex(new RegExp(" + jsString(p) + "))"
					}
				}
			case "oneof":
				quoted := make([]string, len(r.set))
				for i, v := range r.set {
					quoted[i] = jsString(v)
				}
				expr = "z.enum([" + strings.Join(quoted, ", ") + "])"
			}
		case kindNumber:
			switch r.name {
			case "min", "gte":
				expr += ".gte(" + num(r.num) + ")"
			case "max", "lte":
				expr += ".lte(" + num(r.num) + ")"
			case "gt":
				expr += ".gt(" + num(r.num) + ")"
			case "lt":
				expr += ".lt(" + num(r.num) + ")"
			case "oneof":
				lits := make([]string, len(r.nums))
				for i, v := range r.nums {
					lits[i] = "z.literal(" + num(v) + ")"
				}
				if len(lits) == 1 {
					expr = lits[0]
				} else {
					expr = "z.union([" + strings.Join(lits, ", ") + "])"
				}
			}
		case kindList:
			if isMap {
				// z.record has no size checks of its own.
				switch r.name {
				case "min":
					expr += mapSize(">=", r.num)
				case "max":
					expr += mapSize("<=", r.num)
				case "len":
					expr += mapSize("===", r.num)
				}
				continue
			}
			switch r.name {
			case "min":
				expr += ".min(" + num(r.num) + ")"
			case "max":
				expr += ".max(" + num(r.num) + ")"
			case "len":
				expr += ".length(" + num(r.num) + ")"
			}
		}
	}
	return expr
}

// ReactQueryHooks generates TanStack Query (v5) hooks on top of the typed
// client: GET routes become useQuery hooks, every other method a useMutation.
//
//	const { useGetUsers, useCreateUser } = createHooks(createClient({ baseUrl }));
func (a *App) ReactQueryHooks() string {
	g := newTSGen()
	for _, s := range a.specs {
		g.scanInput(s.in, s.method)
		g.scanOutput(s.out)
	}
	g.assignNames()
	var ops []tsOp
	used := map[string]bool{}
	for _, s := range a.specs {
		base := tsIdent(s.opID())
		name := base
		for i := 2; used[name]; i++ {
			name = base + strconv.Itoa(i)
		}
		used[name] = true
		ops = append(ops, g.operation(s, name))
	}

	var b strings.Builder
	b.WriteString(`// Generated by Aemeath. Do not edit manually.
/* eslint-disable */

import { useMutation, useQuery, type UseMutationOptions, type UseQueryOptions } from "@tanstack/react-query";
import { type ApiError, type Client } from "./client";

type Input<K extends keyof Client> = Parameters<Client[K]>[0];
type Output<K extends keyof Client> = Awaited<ReturnType<Client[K]>>;

export function createHooks(client: Client) {
  return {
`)
	for _, op := range ops {
		hook := "use" + upperFirst(op.name)
		q := jsString(op.name)
		isQuery := op.method == "GET" || op.method == "HEAD"
		switch {
		case isQuery && op.mode == noInput:
			fmt.Fprintf(&b, "    %s: (options?: Omit<UseQueryOptions<Output<%s>, ApiError>, \"queryKey\" | \"queryFn\">) =>\n      useQuery<Output<%s>, ApiError>({ queryKey: [%s], queryFn: () => client.%s(), ...options }),\n", hook, q, q, q, op.name)
		case isQuery && op.mode == optionalInput:
			fmt.Fprintf(&b, "    %s: (input?: Input<%s>, options?: Omit<UseQueryOptions<Output<%s>, ApiError>, \"queryKey\" | \"queryFn\">) =>\n      useQuery<Output<%s>, ApiError>({ queryKey: [%s, input], queryFn: () => client.%s(input), ...options }),\n", hook, q, q, q, q, op.name)
		case isQuery:
			fmt.Fprintf(&b, "    %s: (input: Input<%s>, options?: Omit<UseQueryOptions<Output<%s>, ApiError>, \"queryKey\" | \"queryFn\">) =>\n      useQuery<Output<%s>, ApiError>({ queryKey: [%s, input], queryFn: () => client.%s(input), ...options }),\n", hook, q, q, q, q, op.name)
		case op.mode == noInput:
			fmt.Fprintf(&b, "    %s: (options?: Omit<UseMutationOptions<Output<%s>, ApiError, void>, \"mutationFn\">) =>\n      useMutation<Output<%s>, ApiError, void>({ mutationFn: () => client.%s(), ...options }),\n", hook, q, q, op.name)
		default:
			fmt.Fprintf(&b, "    %s: (options?: Omit<UseMutationOptions<Output<%s>, ApiError, Input<%s>>, \"mutationFn\">) =>\n      useMutation<Output<%s>, ApiError, Input<%s>>({ mutationFn: (input) => client.%s(input as never), ...options }),\n", hook, q, q, q, q, op.name)
		}
	}
	b.WriteString("  };\n}\n")
	return b.String()
}

// mapSize checks the number of keys of a z.record, as the server checks the
// length of a map.
func mapSize(op string, n float64) string {
	word := map[string]string{">=": "at least", "<=": "at most", "===": "exactly"}[op]
	return ".refine((v) => Object.keys(v).length " + op + " " + num(n) + ", " + jsString("must contain "+word+" "+num(n)+" items") + ")" // the server's message
}

// hasPositiveMin reports whether a min or len rule already demands at least
// one element, which makes the check for "required" redundant.
func hasPositiveMin(rules []rule) bool {
	for _, r := range rules {
		if (r.name == "min" || r.name == "len") && r.num >= 1 {
			return true
		}
	}
	return false
}

func hasRule(rules []rule, name string) bool {
	for _, r := range rules {
		if r.name == name {
			return true
		}
	}
	return false
}

// zodRange is the range of a Go number type, which encoding/json enforces:
// 128 does not fit an int8 and -1 does not fit a uint, so the server answers
// 400. (int and int64 are left to Zod's own safe-integer range; see the
// documentation on large integers.)
func zodRange(k reflect.Kind) string {
	lo, hi, ok := numberRange(k)
	if !ok {
		return ""
	}
	out := ".gte(" + jsNum(lo) + ")"
	if hi != 0 {
		out += ".lte(" + jsNum(hi) + ")"
	}
	return out
}

// jsNum writes a number for JavaScript, with an exponent when it is large.
func jsNum(f float64) string {
	if math.Abs(f) >= 1e21 {
		return strconv.FormatFloat(f, 'g', -1, 64)
	}
	return num(f)
}
