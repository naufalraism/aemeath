package aemeath

import (
	"fmt"
	"reflect"
	"strconv"
	"strings"
)

// ZodSchemas generates a TypeScript file with Zod schemas for every request
// and response type, plus one schema per operation input (path, query,
// headers, body). The `validate` rules become Zod checks, so a form can be
// validated in the browser with exactly the rules the server enforces.
//
// Note: `pattern` rules are Go (RE2) regular expressions and are passed to
// JavaScript's RegExp unchanged; stick to the common syntax.
func (a *App) ZodSchemas() string {
	g := newTSGen()
	for _, s := range a.specs {
		g.scanInput(s.in, s.method)
		g.scanOutput(s.out)
	}
	g.assignNames()

	var b strings.Builder
	b.WriteString("// Generated by Aemeath. Do not edit manually.\n/* eslint-disable */\n\nimport { z } from \"zod\";\n\n")

	emit := func(name string, e *tsEntry, input bool) {
		fmt.Fprintf(&b, "export interface %s {\n", name)
		for _, line := range g.fields(e.typ, 0, input) {
			fmt.Fprintf(&b, "  %s;\n", line)
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "export const %sSchema: z.ZodType<%s> = z.object({\n", name, name)
		for _, line := range g.zodFields(e.typ, input) {
			fmt.Fprintf(&b, "  %s,\n", line)
		}
		b.WriteString("});\n\n")
	}
	for _, e := range g.order {
		if e.inName != "" {
			emit(e.inName, e, true)
		}
		if e.outName != "" {
			emit(e.outName, e, false)
		}
	}

	// One schema per operation input part.
	used := map[string]bool{}
	for _, s := range a.specs {
		base := tsIdent(s.opID())
		name := base
		for i := 2; used[name]; i++ {
			name = base + strconv.Itoa(i)
		}
		used[name] = true
		inputs := g.zodInputParts(s)
		for _, part := range []string{"Path", "Query", "Headers", "Body"} { // a fixed order keeps the output stable
			lines := inputs[part]
			if len(lines) == 0 {
				continue
			}
			fmt.Fprintf(&b, "export const %s%sSchema = z.object({\n", name, part)
			for _, l := range lines {
				fmt.Fprintf(&b, "  %s,\n", l)
			}
			b.WriteString("});\n\n")
		}
	}
	return b.String()
}

// zodInputParts returns the Zod fields of an operation's path, query, header
// and body inputs, keyed by the suffix of the generated schema name.
func (g *tsGen) zodInputParts(s routeSpec) map[string][]string {
	parts := map[string][]string{"Path": nil, "Query": nil, "Headers": nil, "Body": nil}
	t := s.in
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return parts
	}
	for _, ff := range flatFields(t) {
		f := ff.StructField
		src, pname := paramSource(f)
		key := ""
		name := jsonName(f)
		switch {
		case src == "path":
			key, name = "Path", pname
		case src == "query":
			key, name = "Query", pname
		case src == "header":
			key, name = "Headers", pname
		case src == "cookie":
			continue
		case bodyMethod(s.method):
			key = "Body"
		default:
			continue
		}
		if jsonName(f) == "-" && src == "" {
			continue
		}
		parts[key] = append(parts[key], g.zodFieldNamed(f, name, true))
	}
	return parts
}

func (g *tsGen) zodFields(t reflect.Type, input bool) []string {
	var lines []string
	for _, f := range jsonFields(t) {
		name := jsonName(f)
		if name == "-" {
			continue
		}
		lines = append(lines, g.zodFieldNamed(f, name, input))
	}
	return lines
}

func (g *tsGen) zodFieldNamed(f reflect.StructField, name string, input bool) string {
	expr := g.zodType(f.Type, input)
	if input {
		expr = zodRules(expr, f)
	}
	if (f.Type.Kind() == reflect.Pointer && !(input && hasRequired(f))) || (!input && nilable(f.Type)) {
		expr += ".nullable()"
	}
	optional := hasOmitEmpty(f)
	if input {
		optional = !inputRequired(f)
	}
	if _, src := paramSource(f); src != "" && f.Tag.Get("path") != "" {
		optional = false
	}
	if optional {
		expr += ".optional()"
	}
	return tsKey(name) + ": " + expr
}

func (g *tsGen) zodType(t reflect.Type, input bool) string {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == timeType {
		return `z.string().datetime({ offset: true })`
	}
	if isTextType(t) {
		if t.Name() == "UUID" {
			return "z.string().uuid()"
		}
		return "z.string()"
	}
	switch t.Kind() {
	case reflect.String:
		return "z.string()"
	case reflect.Bool:
		return "z.boolean()"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return "z.number().int()"
	case reflect.Float32, reflect.Float64:
		return "z.number()"
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			return "z.string()"
		}
		return "z.array(" + g.zodType(t.Elem(), input) + ")"
	case reflect.Map:
		return "z.record(z.string(), " + g.zodType(t.Elem(), input) + ")"
	case reflect.Struct:
		if t.Name() != "" {
			name := g.register(t, input)
			return "z.lazy(() => " + name + "Schema)"
		}
		lines := g.zodFields(t, input)
		if len(lines) == 0 {
			return "z.object({})"
		}
		return "z.object({ " + strings.Join(lines, ", ") + " })"
	}
	return "z.unknown()"
}

// zodRules appends the Zod checks that correspond to the `validate` rules of f.
func zodRules(expr string, f reflect.StructField) string {
	if f.Tag.Get("validate") == "" {
		return expr
	}
	_, rules := parseRules(reflect.TypeOf(struct{}{}), f)
	class := classOf(f.Type)
	base := f.Type
	for base.Kind() == reflect.Pointer {
		base = base.Elem()
	}
	isMap := base.Kind() == reflect.Map
	for _, r := range rules {
		switch class {
		case kindString:
			switch r.name {
			case "min":
				expr += ".min(" + num(r.num) + ")"
			case "max":
				expr += ".max(" + num(r.num) + ")"
			case "len":
				expr += ".length(" + num(r.num) + ")"
			case "email":
				expr += ".email()"
			case "url":
				expr += ".url()"
			case "uuid":
				expr += ".uuid()"
			case "pattern":
				expr += ".regex(new RegExp(" + strconv.Quote(r.arg) + "))"
			case "oneof":
				quoted := make([]string, len(r.set))
				for i, v := range r.set {
					quoted[i] = strconv.Quote(v)
				}
				expr = "z.enum([" + strings.Join(quoted, ", ") + "])"
			}
		case kindNumber:
			switch r.name {
			case "min", "gte":
				expr += ".gte(" + num(r.num) + ")"
			case "max", "lte":
				expr += ".lte(" + num(r.num) + ")"
			case "gt":
				expr += ".gt(" + num(r.num) + ")"
			case "lt":
				expr += ".lt(" + num(r.num) + ")"
			case "oneof":
				lits := make([]string, len(r.nums))
				for i, v := range r.nums {
					lits[i] = "z.literal(" + num(v) + ")"
				}
				if len(lits) == 1 {
					expr = lits[0]
				} else {
					expr = "z.union([" + strings.Join(lits, ", ") + "])"
				}
			}
		case kindList:
			if isMap {
				continue // z.record has no size checks
			}
			switch r.name {
			case "min":
				expr += ".min(" + num(r.num) + ")"
			case "max":
				expr += ".max(" + num(r.num) + ")"
			case "len":
				expr += ".length(" + num(r.num) + ")"
			}
		}
	}
	return expr
}

// ReactQueryHooks generates TanStack Query (v5) hooks on top of the typed
// client: GET routes become useQuery hooks, every other method a useMutation.
//
//	const { useGetUsers, useCreateUser } = createHooks(createClient({ baseUrl }));
func (a *App) ReactQueryHooks() string {
	g := newTSGen()
	for _, s := range a.specs {
		g.scanInput(s.in, s.method)
		g.scanOutput(s.out)
	}
	g.assignNames()
	var ops []tsOp
	used := map[string]bool{}
	for _, s := range a.specs {
		base := tsIdent(s.opID())
		name := base
		for i := 2; used[name]; i++ {
			name = base + strconv.Itoa(i)
		}
		used[name] = true
		ops = append(ops, g.operation(s, name))
	}

	var b strings.Builder
	b.WriteString(`// Generated by Aemeath. Do not edit manually.
/* eslint-disable */

import { useMutation, useQuery, type UseMutationOptions, type UseQueryOptions } from "@tanstack/react-query";
import { type ApiError, type Client } from "./client";

type Input<K extends keyof Client> = Parameters<Client[K]>[0];
type Output<K extends keyof Client> = Awaited<ReturnType<Client[K]>>;

export function createHooks(client: Client) {
  return {
`)
	for _, op := range ops {
		hook := "use" + upperFirst(op.name)
		q := strconv.Quote(op.name)
		isQuery := op.method == "GET" || op.method == "HEAD"
		switch {
		case isQuery && op.mode == noInput:
			fmt.Fprintf(&b, "    %s: (options?: Omit<UseQueryOptions<Output<%s>, ApiError>, \"queryKey\" | \"queryFn\">) =>\n      useQuery<Output<%s>, ApiError>({ queryKey: [%s], queryFn: () => client.%s(), ...options }),\n", hook, q, q, q, op.name)
		case isQuery && op.mode == optionalInput:
			fmt.Fprintf(&b, "    %s: (input?: Input<%s>, options?: Omit<UseQueryOptions<Output<%s>, ApiError>, \"queryKey\" | \"queryFn\">) =>\n      useQuery<Output<%s>, ApiError>({ queryKey: [%s, input], queryFn: () => client.%s(input), ...options }),\n", hook, q, q, q, q, op.name)
		case isQuery:
			fmt.Fprintf(&b, "    %s: (input: Input<%s>, options?: Omit<UseQueryOptions<Output<%s>, ApiError>, \"queryKey\" | \"queryFn\">) =>\n      useQuery<Output<%s>, ApiError>({ queryKey: [%s, input], queryFn: () => client.%s(input), ...options }),\n", hook, q, q, q, q, op.name)
		case op.mode == noInput:
			fmt.Fprintf(&b, "    %s: (options?: Omit<UseMutationOptions<Output<%s>, ApiError, void>, \"mutationFn\">) =>\n      useMutation<Output<%s>, ApiError, void>({ mutationFn: () => client.%s(), ...options }),\n", hook, q, q, op.name)
		default:
			fmt.Fprintf(&b, "    %s: (options?: Omit<UseMutationOptions<Output<%s>, ApiError, Input<%s>>, \"mutationFn\">) =>\n      useMutation<Output<%s>, ApiError, Input<%s>>({ mutationFn: (input) => client.%s(input as never), ...options }),\n", hook, q, q, q, q, op.name)
		}
	}
	b.WriteString("  };\n}\n")
	return b.String()
}
